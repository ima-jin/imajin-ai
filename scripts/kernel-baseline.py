#!/usr/bin/env python3
"""Generate/verify the kernel cut using network-isolated scratch PostgreSQL only."""
import argparse
import hashlib
import json
import pathlib
import re
import shutil
import subprocess
import tempfile
import time
import uuid

ROOT = pathlib.Path(__file__).resolve().parent.parent
MIGRATIONS = ROOT / "migrations"
ARCHIVE = MIGRATIONS / "archive/pre-kernel-baseline"
IMAGE = "postgres:16-bookworm@sha256:0ea6700a3b4f0ae6ce746519073558aed4d88a79d8d07622a9a644946c7319c4"
SCHEMAS = sorted([
    "auth", "chat", "connections", "consent_requests", "github", "inference",
    "kernel", "media", "money", "notify", "operator", "pay", "profile",
    "registry", "relay", "usage", "www",
])
# Only static configuration/public-client sentinels produced by empty-history
# replay. No runtime users, credentials, grants, balances or node provisioning.
SEEDS = [
    "auth.attestation_type_registry", "auth.identities", "kernel.bus_chain_configs",
    "notify.templates", "registry.apps", "usage.emitters",
]
BASELINE = "0001_kernel_baseline.sql"
MANIFEST = "kernel-baseline.json"
CUT_THROUGH = "0215_registry_apps_sign_in_audience.sql"
EXTENSIONS = "SELECT extname,extversion,n.nspname FROM pg_extension e JOIN pg_namespace n ON n.oid=e.extnamespace ORDER BY extname"
DOCKER = shutil.which("docker") or "/usr/bin/docker"


def run(*args, content=None):
    completed = subprocess.run(
        args, input=content, text=True, check=True,
        stdout=subprocess.PIPE, stderr=subprocess.PIPE,
    )
    return completed.stdout


class Scratch:
    def __init__(self):
        self.container = run(
            DOCKER, "run", "--detach", "--rm", "--network", "none",
            "--tmpfs", "/var/lib/postgresql/data:rw",
            "-e", "POSTGRES_HOST_AUTH_METHOD=trust", IMAGE, "-c", "autovacuum=off",
        ).strip()

    def ready(self):
        for _ in range(60):
            try:
                self.sql("postgres", "SELECT 1")
                return
            except subprocess.CalledProcessError:
                time.sleep(1)
        raise RuntimeError("Scratch PostgreSQL startup timed out")

    def sql(self, db, content):
        return run(
            DOCKER, "exec", "-i", self.container, "psql", "-X", "-qAt",
            "-U", "postgres", "-d", db, "--set=ON_ERROR_STOP=1",
            *([] if content.startswith("CREATE DATABASE ") else ["--single-transaction"]),
            content=content,
        )

    def dump(self, db):
        dump = run(
            DOCKER, "exec", self.container, "pg_dump", "-U", "postgres",
            "-d", db, "--schema-only", "--no-owner", "--no-privileges",
            *[f"--schema={schema}" for schema in SCHEMAS],
        )
        # pg_dump emits random restrict tokens and patch-version comments.
        # Neither is catalog content. All DDL and session settings are retained.
        return "\n".join(
            line for line in dump.splitlines()
            if not line.startswith(("\\restrict ", "\\unrestrict ", "-- Dumped "))
        ).strip() + "\n"

    def close(self):
        run(DOCKER, "rm", "-f", self.container)


def normalized_seed(table, row):
    if table == "kernel.bus_chain_configs":
        row["id"] = str(uuid.uuid5(uuid.NAMESPACE_URL, f"imajin:baseline:chain:{row['event_type']}:{row['scope']}"))
    if table == "notify.templates":
        row["id"] = str(uuid.uuid5(uuid.NAMESPACE_URL, f"imajin:baseline:template:{row['scope']}"))
    # History uses now() defaults; fix only seed bookkeeping timestamps.
    for column in ("created_at", "updated_at"):
        if row.get(column) is not None:
            row[column] = "2000-01-01T00:00:00+00:00"
    return json.dumps(row, sort_keys=True, separators=(",", ":"))


def seed_rows(scratch, db):
    result = []
    for table in SEEDS:
        rows = scratch.sql(db, f"SELECT to_jsonb(t)::text FROM {table} t ORDER BY to_jsonb(t)::text")
        for line in rows.splitlines():
            result.append((table, normalized_seed(table, json.loads(line))))
    return sorted(result)


def baseline(scratch):
    for schema in SCHEMAS:
        tables = scratch.sql("history", f"""
            SELECT tablename FROM pg_tables WHERE schemaname='{schema}' ORDER BY tablename
        """)
        for table in tables.splitlines():
            qualified = f"{schema}.{table}"
            if qualified not in SEEDS:
                count = scratch.sql("history", f'SELECT count(*) FROM "{schema}"."{table}"')
                if count.strip() != "0":
                    raise RuntimeError(f"Unlisted seed target {qualified}: review and declare required seed rows")
    result = "-- owner: kernel\n-- Generated by python3 scripts/kernel-baseline.py generate; do not edit.\n"
    result += f"-- Historical cut: {CUT_THROUGH}; later root migrations remain active.\n"
    result += "CREATE EXTENSION IF NOT EXISTS pgcrypto WITH SCHEMA public;\n"
    result += scratch.dump("history")
    result += "\n-- Required static seeds; see migrations/BASELINE.md.\n"
    for table, row in seed_rows(scratch, "history"):
        literal = row.replace("'", "''")
        result += f"INSERT INTO {table} SELECT * FROM jsonb_populate_record(NULL::{table}, '{literal}'::jsonb);\n"
    return result


def apply_migration(scratch, db, file, checksum_override=None):
    content = file.read_text()
    digest = checksum_override or hashlib.sha256(file.read_bytes()).hexdigest()
    scratch.sql(db, content + f"\nINSERT INTO public._migrations(filename,checksum) VALUES ('{file.name}','{digest}');")


def replay(scratch, files, db="history", overrides=None):
    scratch.sql("postgres", f"CREATE DATABASE {db}")
    scratch.sql(db, """CREATE TABLE public._migrations (
        id SERIAL PRIMARY KEY, filename TEXT UNIQUE NOT NULL,
        checksum TEXT NOT NULL, applied_at TIMESTAMPTZ DEFAULT NOW())""")
    for file in files:
        apply_migration(scratch, db, file, (overrides or {}).get(file.name))
    print(f"Replayed {len(files)} unchanged migrations through {files[-1].name} into {db}", flush=True)


def validate_variant(variant, canonical):
    if not re.fullmatch(r"[a-f0-9]{64}", variant.get("checksum", "")):
        raise RuntimeError("Recorded checksum variants must be exact SHA-256 values")
    if variant["checksum"] == canonical:
        raise RuntimeError("Recorded checksum variants must be extra, not canonical")
    if not variant.get("observedIn") or not set(variant["observedIn"]) <= {"dev", "prod"}:
        raise RuntimeError("Recorded checksum variants need observed environments")
    if not variant.get("reason") or not variant.get("evidence"):
        raise RuntimeError("Recorded checksum variants need rationale and review provenance")


def accepted_checksums(files):
    existing = json.loads((MIGRATIONS / MANIFEST).read_text())
    accepted = existing.get("acceptedHistoricalChecksums", {})
    canonical = {file.name: hashlib.sha256(file.read_bytes()).hexdigest() for file in files}
    if set(accepted) - set(canonical):
        raise RuntimeError("Recorded checksum variants must reference pre-cut migrations")
    for variants in accepted.values():
        if not variants:
            raise RuntimeError("Recorded checksum variants cannot be empty")
    for name, variants in accepted.items():
        for variant in variants:
            validate_variant(variant, canonical[name])
    return dict(sorted(accepted.items()))


def generate(scratch, files, check):
    content = baseline(scratch)
    manifest = {
        "filename": BASELINE, "archive": "archive/pre-kernel-baseline",
        "schemas": SCHEMAS, "seeds": SEEDS,
        "acceptedHistoricalChecksums": accepted_checksums(files),
        "migrations": [
            {"filename": file.name, "checksum": hashlib.sha256(file.read_bytes()).hexdigest()}
            for file in files
        ],
    }
    outputs = {
        MIGRATIONS / BASELINE: content,
        MIGRATIONS / MANIFEST: json.dumps(manifest, indent=2) + "\n",
    }
    for path, expected in outputs.items():
        if check:
            if path.read_text() != expected:
                raise RuntimeError(f"{path.name} is stale; regenerate after rebasing")
        else:
            path.write_text(expected)
    return content


def verify(scratch, content):
    scratch.sql("postgres", "CREATE DATABASE fresh")
    scratch.sql("fresh", content)
    if scratch.dump("history") != scratch.dump("fresh"):
        raise RuntimeError("Full-history and baseline kernel catalogs differ")
    if scratch.sql("history", EXTENSIONS) != scratch.sql("fresh", EXTENSIONS):
        raise RuntimeError("Full-history and baseline required extensions differ")
    for db in ("history", "fresh"):
        membership_index = scratch.sql(db, """
            SELECT indisunique AND indisvalid AND pg_get_indexdef(indexrelid) =
              'CREATE UNIQUE INDEX idx_conv_members_unique ON chat.conversation_members USING btree (conversation_did, member_did)'
            FROM pg_index WHERE indexrelid = 'chat.idx_conv_members_unique'::regclass
        """)
        if membership_index.strip() != "t":
            raise RuntimeError(f"{db}: migration 0216 membership unique index is missing or differs")
    if seed_rows(scratch, "history") != seed_rows(scratch, "fresh"):
        raise RuntimeError("Full-history and baseline static seed rows differ")
    apps = scratch.sql("fresh", """SELECT nspname FROM pg_namespace
        WHERE nspname IN ('coffee','dykil','events','learn','links','market')""")
    if apps.strip():
        raise RuntimeError("Fresh kernel contains app-owned schemas")
    print("PASS: baseline alone matches pre-cut history through 0215; catalogs/static seeds match; no app schemas", flush=True)
    print("PASS: pre-cut history and baseline-only init retain the valid membership unique index; 0216 stays post-cut", flush=True)
    scratch.sql("postgres", "CREATE DATABASE full_history TEMPLATE history")
    for file in post_cut_files():
        apply_migration(scratch, "full_history", file)
        scratch.sql("fresh", file.read_text())
    if scratch.dump("full_history") != scratch.dump("fresh"):
        raise RuntimeError("Baseline plus post-cut migrations differs from full-history replay")
    if seed_rows(scratch, "full_history") != seed_rows(scratch, "fresh"):
        raise RuntimeError("Baseline plus post-cut static seeds differ from full-history replay")
    print("PASS: baseline plus all post-cut migrations matches full replay through the last root migration", flush=True)


def install_runner(scratch):
    """Copy only known source/dependencies, never a checkout or env files."""
    run(DOCKER, "exec", scratch.container, "mkdir", "-p",
        "/verify/scripts/lib", "/verify/migrations", "/verify/apps/kernel", "/verify/node_modules")
    run(DOCKER, "cp", shutil.which("node"), f"{scratch.container}:/usr/local/bin/node")
    for name in ("migrate.mjs", "env-utils.js"):
        run(DOCKER, "cp", str(ROOT / "scripts" / name), f"{scratch.container}:/verify/scripts/{name}")
    for name in ("kernel-baseline.mjs", "migrate-owner-filter.mjs", "migration-schema-scan.mjs",
                 "migration-ownership-parser.mjs", "sequential.mjs"):
        run(DOCKER, "cp", str(ROOT / "scripts/lib" / name), f"{scratch.container}:/verify/scripts/lib/{name}")
    for name in (BASELINE, MANIFEST, *[file.name for file in post_cut_files()]):
        run(DOCKER, "cp", str(MIGRATIONS / name), f"{scratch.container}:/verify/migrations/{name}")
    dependency = (ROOT / "node_modules/postgres").resolve(strict=True)
    run(DOCKER, "cp", str(dependency), f"{scratch.container}:/verify/node_modules/postgres")


def scratch_file(scratch, destination, content):
    with tempfile.NamedTemporaryFile(mode="w") as temporary:
        temporary.write(content)
        temporary.flush()
        run(DOCKER, "cp", temporary.name, f"{scratch.container}:{destination}")


def migrate(scratch, db):
    # This URL exists exclusively inside a network-none container.
    return run(DOCKER, "exec", "-e", f"DATABASE_URL=postgres://postgres@localhost/{db}",
               scratch.container, "node", "/verify/scripts/migrate.mjs")


def ledger_state(scratch, db):
    rows = scratch.sql(db, "SELECT to_jsonb(t)::text FROM public._migrations t ORDER BY filename")
    return [json.loads(row) for row in rows.splitlines()]


def snapshot(scratch, db, ignore_filenames=()):
    objects = scratch.sql(db, """
        SELECT n.nspname,c.relname,c.oid,c.relfilenode FROM pg_class c
        JOIN pg_namespace n ON n.oid=c.relnamespace
        WHERE n.nspname NOT IN ('pg_catalog','information_schema','pg_toast','public')
        ORDER BY 1,2;
        SELECT xmin::text,to_jsonb(t) FROM chat.conversation_reads_v2 t;
        SELECT xmin::text,to_jsonb(t) FROM events.events t;
    """)
    ignored = {BASELINE, *ignore_filenames}
    ledger = [row for row in ledger_state(scratch, db) if row["filename"] not in ignored]
    return objects + json.dumps(ledger, sort_keys=True)

def all_data(scratch, db, normalize_seeds=False):
    dump = run(DOCKER, "exec", scratch.container, "pg_dump", "-U", "postgres",
               "-d", db, "--data-only", "--no-owner", "--no-privileges",
               "--exclude-table=public._migrations*",
               *([f"--exclude-table-data={table}" for table in SEEDS] if normalize_seeds else []))
    data = "\n".join(line for line in dump.splitlines()
                     if not line.startswith(("\\restrict ", "\\unrestrict ")))
    return data + (json.dumps(seed_rows(scratch, db)) if normalize_seeds else "")

def relation_identities(scratch, db):
    rows = scratch.sql(db, """
        SELECT n.nspname || '.' || c.relname, c.oid, c.relfilenode FROM pg_class c
        JOIN pg_namespace n ON n.oid=c.relnamespace
        WHERE n.nspname NOT IN ('pg_catalog','information_schema','pg_toast','public')
        ORDER BY 1
    """)
    return {name: (oid, node) for name, oid, node in (row.split("|") for row in rows.splitlines())}


def verify_adoption(scratch, db, files=None):
    files = post_cut_files() if files is None else files
    historical = ledger_state(scratch, db)
    tracked = {row["filename"] for row in historical}
    pending = [file for file in files if file.name not in tracked]
    missing_post = {file.name: hashlib.sha256(file.read_bytes()).hexdigest()
                    for file in pending}
    original_identities = relation_identities(scratch, db)
    # Clone the restored history/data, then independently replay every pending
    # root migration. Adoption itself adds no DDL; post-cut SQL legitimately can.
    expected = f"expected_{uuid.uuid4().hex}"
    scratch.sql("postgres", f"CREATE DATABASE {expected} TEMPLATE {db}")
    for file in pending:
        apply_migration(scratch, expected, file)
    first = migrate(scratch, db)
    if (scratch.dump(db) != scratch.dump(expected)
            or all_data(scratch, db, bool(pending)) != all_data(scratch, expected, bool(pending))
            or scratch.sql(db, EXTENSIONS) != scratch.sql(expected, EXTENSIONS)):
        raise RuntimeError("Adoption differs from restored history plus all pending post-cut migrations")
    replayed_identities = relation_identities(scratch, expected)
    adopted_identities = relation_identities(scratch, db)
    if any(adopted_identities.get(name) != identity for name, identity in original_identities.items()
           if replayed_identities.get(name) == identity):
        raise RuntimeError("Adoption changed object identities untouched by pending post-cut migrations")
    adopted = ledger_state(scratch, db)
    if [row for row in adopted if row["filename"] in tracked] != historical:
        raise RuntimeError("Adoption changed historical ledger rows")
    count = scratch.sql(db, f"SELECT count(*) FROM public._migrations WHERE filename='{BASELINE}'")
    if count.strip() != "1":
        raise RuntimeError("Adoption must record exactly one baseline row")
    additions = {row["filename"]: row["checksum"] for row in adopted if row["filename"] not in tracked}
    expected_additions = dict(missing_post)
    if BASELINE not in tracked:
        expected_additions[BASELINE] = hashlib.sha256((MIGRATIONS / BASELINE).read_bytes()).hexdigest()
    if additions != expected_additions:
        raise RuntimeError("Adoption must record only the baseline and all pending canonical post-cut rows")
    # After pending SQL has run, the second invocation must be a strict no-op,
    # including object identities, row xmin, raw data and the entire ledger.
    before = (snapshot(scratch, db), scratch.dump(db), all_data(scratch, db),
              scratch.sql(db, EXTENSIONS), adopted)
    migrate(scratch, db)
    after = (snapshot(scratch, db), scratch.dump(db), all_data(scratch, db),
             scratch.sql(db, EXTENSIONS), ledger_state(scratch, db))
    if after != before:
        raise RuntimeError("Repeated adoption changed ledger, object identities, data or schema")
    return first


def recorded_ledger_checks(scratch):
    manifest = json.loads((MIGRATIONS / MANIFEST).read_text())
    variants = manifest["acceptedHistoricalChecksums"]
    for environment in ("dev", "prod"):
        overrides = {name: variant["checksum"] for name, entries in variants.items()
                     for variant in entries if environment in variant["observedIn"]}
        files = history_files("check") + (post_cut_files() if environment == "dev" else [])
        db = f"recorded_{environment}"
        replay(scratch, files, db, overrides)
        output = verify_adoption(scratch, db)
        expected = "already applied" if environment == "dev" else "applying..."
        for file in post_cut_files():
            if f"{file.name} — {expected}" not in output:
                raise RuntimeError(f"{environment}: {file.name} post-cut apply/skip behavior differs")
        print(f"PASS: recorded {environment} ledger variants preserved; all post-cut files {expected}", flush=True)
    replay(scratch, history_files("check"), "unrecorded", {"0001_seed.sql": "0" * 64})
    before = snapshot(scratch, "unrecorded")
    try:
        migrate(scratch, "unrecorded")
    except subprocess.CalledProcessError as error:
        if "Historical checksum mismatch: 0001_seed.sql" not in error.stderr:
            raise RuntimeError("Unrecorded checksum did not fail with the expected diagnostic") from error
    else:
        raise RuntimeError("Unrecorded checksum was accepted")
    if snapshot(scratch, "unrecorded") != before:
        raise RuntimeError("Unrecorded checksum refusal changed the ledger or database")
    print("PASS: unrecorded checksum refuses without changing historical ledger rows", flush=True)

def runner_checks(scratch):
    install_runner(scratch)
    scratch.sql("postgres", "CREATE DATABASE initialized")
    migrate(scratch, "initialized")
    migrate(scratch, "initialized")
    if scratch.dump("initialized") != scratch.dump("full_history"):
        raise RuntimeError("Runner fresh initialization catalog mismatch")
    scratch.sql("history", (ROOT / "scripts/seed-drift-fixture.sql").read_text())
    scratch.sql("history", """INSERT INTO events.events
        (id,did,public_key,creator_did,title,starts_at)
        VALUES ('fixture:event','fixture:event','synthetic-public','fixture:creator',
                'Restore preservation fixture','2000-01-01')""")
    dump = run(DOCKER, "exec", scratch.container, "pg_dump", "-U", "postgres",
               "-d", "history", "--no-owner", "--no-privileges")
    scratch.sql("postgres", "CREATE DATABASE restored")
    scratch.sql("restored", dump)
    verify_adoption(scratch, "restored")
    run(DOCKER, "exec", scratch.container, "pg_dump", "-U", "postgres",
        "-d", "history", "--format=custom", "--file=/synthetic.dump")
    with tempfile.TemporaryDirectory() as temporary:
        backup = pathlib.Path(temporary) / "synthetic.dump"
        run(DOCKER, "cp", f"{scratch.container}:/synthetic.dump", str(backup))
        restore_check(scratch, backup)
    recorded_ledger_checks(scratch)
    for db, mutation in (
        ("partial", "DELETE FROM public._migrations WHERE filename LIKE '0201_%'"),
        ("tampered", "UPDATE public._migrations SET checksum='bad' WHERE filename LIKE '0201_%'"),
        ("untracked", "TRUNCATE public._migrations"),
    ):
        scratch.sql("postgres", f"CREATE DATABASE {db} TEMPLATE history")
        scratch.sql(db, mutation)
        previous = snapshot(scratch, db)
        try:
            migrate(scratch, db)
        except subprocess.CalledProcessError:
            if snapshot(scratch, db) != previous:
                raise RuntimeError(f"{db} refusal mutated database")
        else:
            raise RuntimeError(f"{db} database was not refused")
    for db, ddl in (("app_only", "CREATE SCHEMA events; CREATE TABLE events.fixture(id int)"),
                    ("public_only", "CREATE TABLE public.fixture(id int)")):
        scratch.sql("postgres", f"CREATE DATABASE {db}")
        scratch.sql(db, ddl)
        try:
            migrate(scratch, db)
        except subprocess.CalledProcessError:
            pass
        else:
            raise RuntimeError(f"Untracked {db} database was not refused")
    with tempfile.TemporaryDirectory() as temporary:
        probes = []
        for name, content in (
            ("9998_baseline_probe.sql", "CREATE TABLE kernel.baseline_probe(id integer);"),
            ("9999_baseline_probe_column.sql", "ALTER TABLE kernel.baseline_probe ADD COLUMN label text;"),
        ):
            file = pathlib.Path(temporary) / name
            file.write_text("-- owner: kernel\n" + content)
            scratch_file(scratch, f"/verify/migrations/{name}", file.read_text())
            probes.append(file)
        # Start without a baseline row so both schema changes run on adoption.
        scratch.sql("postgres", "CREATE DATABASE multiple_post_cut TEMPLATE history")
        verify_adoption(scratch, "multiple_post_cut", post_cut_files() + probes)
        verify_adoption(scratch, "initialized", post_cut_files() + probes)
    print("PASS: two schema-changing post-cut files replay on adoption and repeat without mutation", flush=True)
    print("PASS: actual runner fresh/repeat, dump-restore adoption, data/ledger preservation, partial/checksum/untracked refusal, all post-cut migrations", flush=True)
def restore_check(scratch, dump):
    install_runner(scratch)
    scratch.sql("postgres", "CREATE DATABASE supplied_restore")
    run(DOCKER, "cp", str(dump.resolve(strict=True)), f"{scratch.container}:/restore.dump")
    run(DOCKER, "exec", scratch.container, "pg_restore", "-U", "postgres",
        "-d", "supplied_restore", "--no-owner", "--no-privileges", "--exit-on-error", "/restore.dump")
    verify_adoption(scratch, "supplied_restore")
    print("PASS: supplied restore plus all pending post-cut migrations matches replay; historical ledger preserved; repeat is mutation-free", flush=True)


def post_cut_files():
    return sorted(file for file in MIGRATIONS.glob("[0-9][0-9][0-9][0-9]_*.sql")
                  if file.name > CUT_THROUGH)


def history_files(mode):
    files = sorted(ARCHIVE.glob("*.sql"))
    if mode == "generate":
        files += [file for file in MIGRATIONS.glob("[0-9][0-9][0-9][0-9]_*.sql")
                  if file.name != BASELINE and file.name <= CUT_THROUGH]
    if any(file.name > CUT_THROUGH for file in files):
        raise RuntimeError("Archive exceeds explicit 0215 cut; keep 0216 in root migrations")
    return sorted(files, key=lambda file: file.name)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("mode", choices=["generate", "check", "restore"])
    parser.add_argument("--dump", type=pathlib.Path, help="Operator-provided custom-format dev backup; restore mode only")
    args = parser.parse_args()
    if (args.mode == "restore") != (args.dump is not None):
        parser.error("restore requires --dump; other modes never accept external data")
    ARCHIVE.mkdir(parents=True, exist_ok=True)
    files = history_files(args.mode)
    scratch = Scratch()
    try:
        scratch.ready()
        if args.mode == "restore":
            restore_check(scratch, args.dump)
            return
        replay(scratch, files)
        content = generate(scratch, files, args.mode == "check")
        verify(scratch, content)
        if args.mode == "check":
            runner_checks(scratch)
        if args.mode == "generate":
            for file in files:
                if file.parent == MIGRATIONS:
                    file.rename(ARCHIVE / file.name)
    finally:
        scratch.close()


if __name__ == "__main__":
    try:
        main()
    except subprocess.CalledProcessError as error:
        raise SystemExit(f"Scratch command failed: {error.stderr}") from error
